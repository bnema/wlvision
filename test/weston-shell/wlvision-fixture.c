static void
registry_global(void *data, struct wl_registry *registry, uint32_t name,
		const char *interface, uint32_t version)
{
	struct fixture *fixture = data;

	if (strcmp(interface, wl_compositor_interface.name) == 0) {
		fixture->compositor = wl_registry_bind(
			registry, name, &wl_compositor_interface,
			version < 4 ? version : 4);
	} else if (strcmp(interface, wl_shm_interface.name) == 0) {
		fixture->shm = wl_registry_bind(registry, name,
						&wl_shm_interface, 1);
	} else if (strcmp(interface, xdg_wm_base_interface.name) == 0) {
		fixture->wm_base = wl_registry_bind(
			registry, name, &xdg_wm_base_interface, 1);
		xdg_wm_base_add_listener(fixture->wm_base, &wm_base_listener,
					 fixture);
	} else if (fixture->report_input &&
		   strcmp(interface, wl_seat_interface.name) == 0) {
		fixture->seat_version = version < 5 ? version : 5;
		fixture->seat = wl_registry_bind(
			registry, name, &wl_seat_interface,
			fixture->seat_version);
		wl_seat_add_listener(fixture->seat, &seat_listener, fixture);
	}
}

