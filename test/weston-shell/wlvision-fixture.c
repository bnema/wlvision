/* One surface configure is the pair (xdg_surface.configure with the serial,
 * xdg_toplevel.configure with the size and states).  Act once both halves of
 * the newest pair are in. */
static void
handle_configure(struct fixture *fixture)
{
	int width = fixture->configured_width > 0 ?
		fixture->configured_width : fixture->width;
	int height = fixture->configured_height > 0 ?
		fixture->configured_height : fixture->height;

	fixture->have_surface_configure = false;
	fixture->have_toplevel_configure = false;
	fixture->configure_count++;

	report("configure n=%d width=%d height=%d activated=%s",
	       fixture->configure_count, width, height,
	       fixture->activated ? "yes" : "no");

	xdg_surface_ack_configure(fixture->xdg_surface,
				  fixture->configure_serial);

	/* A window must exist in every mode: the first configure always gets a
	 * matching buffer. */
	if (!fixture->have_mapped) {
		fixture->have_mapped = true;
		commit_frame(fixture, width, height);
		return;
	}

	if (width == fixture->cur_width && height == fixture->cur_height)
		return;

	fixture->resize_seen = true;
	fixture->pending_width = width;
	fixture->pending_height = height;

	switch (fixture->resize_mode) {
	case RESIZE_COOPERATIVE:
	case RESIZE_NONE:
		commit_frame(fixture, width, height);
		break;
	case RESIZE_DELAYED:
		if (fixture->resize_delay_ms <= 0) {
			commit_frame(fixture, width, height);
		} else {
			fixture->resize_pending = true;
			fixture->resize_deadline =
				now_ms() + fixture->resize_delay_ms;
		}
		break;
	case RESIZE_IGNORE:
		/* Acknowledge, but keep the old buffer: never commit a
		 * matching one. */
		break;
	case RESIZE_EXIT:
		/* Destruction during a resize: leave without a new buffer. */
		fixture->done = true;
		break;
	}
}

