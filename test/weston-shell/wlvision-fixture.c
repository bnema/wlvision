static void
keyboard_key(void *data, struct wl_keyboard *keyboard, uint32_t serial,
	     uint32_t time, uint32_t key, uint32_t state)
{
	struct fixture *fixture = data;
	char text[64];
	bool pressed = state == WL_KEYBOARD_KEY_STATE_PRESSED;
	int n = 0;

	(void) keyboard;
	(void) serial;
	(void) time;

	if (fixture->xkb_state != NULL)
		n = xkb_state_key_get_utf8(fixture->xkb_state, key + 8, text,
					   sizeof text);

	report("key keycode=%u state=%s utf8=%s", key,
	       pressed ? "pressed" : "released", n > 0 ? text : "none");

	if (fixture->xkb_state != NULL)
		xkb_state_update_key(fixture->xkb_state, key + 8,
				     pressed ? XKB_KEY_DOWN : XKB_KEY_UP);
}

