static void
usage(const char *argv0)
{
	fprintf(stderr,
		"usage: %s [--title NAME] [--app-id ID] [--width N] [--height N]\n"
		"          [--frames N] [--period MS] [--animate]\n"
		"          [--resize cooperative|delayed|ignore|exit|none]\n"
		"          [--resize-delay MS] [--report-input] [--exit-after MS]\n",
		argv0);
}

static enum resize_mode
parse_resize_mode(const char *value)
{
	if (strcmp(value, "cooperative") == 0)
		return RESIZE_COOPERATIVE;
	if (strcmp(value, "delayed") == 0)
		return RESIZE_DELAYED;
	if (strcmp(value, "ignore") == 0)
		return RESIZE_IGNORE;
	if (strcmp(value, "exit") == 0)
		return RESIZE_EXIT;
	if (strcmp(value, "none") == 0)
		return RESIZE_NONE;
	fprintf(stderr, REPORT_PREFIX "unknown --resize mode '%s'\n", value);
	exit(EXIT_FAILURE);
}

static void
parse_arguments(struct fixture *fixture, int argc, char *argv[])
{
	static const struct option options[] = {
		{ "title", required_argument, NULL, 't' },
		{ "app-id", required_argument, NULL, 'a' },
		{ "width", required_argument, NULL, 'w' },
		{ "height", required_argument, NULL, 'h' },
		{ "frames", required_argument, NULL, 'f' },
		{ "period", required_argument, NULL, 'p' },
		{ "animate", no_argument, NULL, 'A' },
		{ "resize", required_argument, NULL, 'r' },
		{ "resize-delay", required_argument, NULL, 'd' },
		{ "report-input", no_argument, NULL, 'i' },
		{ "exit-after", required_argument, NULL, 'e' },
		{ NULL, 0, NULL, 0 },
	};
	int opt;

	fixture->title = DEFAULT_TITLE;
	fixture->app_id = DEFAULT_APP_ID;
	fixture->width = DEFAULT_WIDTH;
	fixture->height = DEFAULT_HEIGHT;
	fixture->frames = 1;
	fixture->period_ms = 40;
	fixture->animate = false;
	fixture->resize_mode = RESIZE_COOPERATIVE;
	fixture->resize_delay_ms = 300;
	fixture->report_input = false;
	fixture->exit_after_ms = 0;

	while ((opt = getopt_long(argc, argv, "", options, NULL)) != -1) {
		switch (opt) {
		case 't':
			fixture->title = optarg;
			break;
		case 'a':
			fixture->app_id = optarg;
			break;
		case 'w':
			fixture->width = atoi(optarg);
			break;
		case 'h':
			fixture->height = atoi(optarg);
			break;
		case 'f':
			fixture->frames = atoi(optarg);
			break;
		case 'p':
			fixture->period_ms = atoi(optarg);
			break;
		case 'A':
			fixture->animate = true;
			break;
		case 'r':
			fixture->resize_mode = parse_resize_mode(optarg);
			break;
		case 'd':
			fixture->resize_delay_ms = atoi(optarg);
			break;
		case 'i':
			fixture->report_input = true;
			break;
		case 'e':
			fixture->exit_after_ms = atoi(optarg);
			break;
		default:
			usage(argv[0]);
			exit(EXIT_FAILURE);
		}
	}

	if (fixture->width <= 0 || fixture->height <= 0 ||
	    fixture->frames < 0 || fixture->period_ms < 0 ||
	    fixture->resize_delay_ms < 0 || fixture->exit_after_ms < 0) {
		fprintf(stderr, REPORT_PREFIX "invalid numeric argument\n");
		exit(EXIT_FAILURE);
	}
}

int
main(int argc, char *argv[])
{
	struct fixture fixture = { 0 };

	parse_arguments(&fixture, argc, argv);
	fixture.start_ms = now_ms();

	fixture.display = wl_display_connect(NULL);
	if (fixture.display == NULL) {
		fprintf(stderr, REPORT_PREFIX
			"cannot connect to wayland\n");
		return EXIT_FAILURE;
	}
	report("connected");

	fixture.registry = wl_display_get_registry(fixture.display);
	wl_registry_add_listener(fixture.registry, &registry_listener, &fixture);
	if (wl_display_roundtrip(fixture.display) < 0) {
		fprintf(stderr, REPORT_PREFIX "registry roundtrip failed\n");
		return EXIT_FAILURE;
	}

	if (fixture.compositor == NULL || fixture.shm == NULL ||
	    fixture.wm_base == NULL) {
		fprintf(stderr, REPORT_PREFIX "missing globals "
			"(compositor=%p shm=%p xdg_wm_base=%p)\n",
			(void *) fixture.compositor, (void *) fixture.shm,
			(void *) fixture.wm_base);
		return EXIT_FAILURE;
	}

	if (fixture.report_input) {
		if (fixture.seat == NULL) {
			fprintf(stderr, REPORT_PREFIX "missing wl_seat global\n");
			return EXIT_FAILURE;
		}
		fixture.xkb_context = xkb_context_new(XKB_CONTEXT_NO_FLAGS);
		if (fixture.xkb_context == NULL) {
			fprintf(stderr, REPORT_PREFIX
				"xkb_context_new failed\n");
			return EXIT_FAILURE;
		}
	}

	fixture.surface = wl_compositor_create_surface(fixture.compositor);
	fixture.xdg_surface = xdg_wm_base_get_xdg_surface(fixture.wm_base,
							   fixture.surface);
	xdg_surface_add_listener(fixture.xdg_surface, &xdg_surface_listener,
				 &fixture);
	fixture.toplevel = xdg_surface_get_toplevel(fixture.xdg_surface);
	xdg_toplevel_add_listener(fixture.toplevel, &xdg_toplevel_listener,
				  &fixture);
	xdg_toplevel_set_title(fixture.toplevel, fixture.title);
	xdg_toplevel_set_app_id(fixture.toplevel, fixture.app_id);
	wl_surface_commit(fixture.surface);

	run(&fixture);

	/* Let the server observe the last commit; a compositor that vanished
	 * during the run is a normal shutdown, not a fixture failure. */
	if (wl_display_flush(fixture.display) < 0)
		(void) 0;
	if (wl_display_roundtrip(fixture.display) < 0)
		fputs(REPORT_PREFIX "compositor gone before shutdown\n", stderr);

	report("done frames=%d configures=%d", fixture.frame_count,
	       fixture.configure_count);

	if (fixture.frame_callback != NULL)
		wl_callback_destroy(fixture.frame_callback);
	if (fixture.keyboard != NULL)
		wl_keyboard_destroy(fixture.keyboard);
	if (fixture.pointer != NULL)
		wl_pointer_destroy(fixture.pointer);
	if (fixture.seat != NULL)
		wl_seat_destroy(fixture.seat);
	if (fixture.toplevel != NULL)
		xdg_toplevel_destroy(fixture.toplevel);
	if (fixture.xdg_surface != NULL)
		xdg_surface_destroy(fixture.xdg_surface);
	if (fixture.surface != NULL)
		wl_surface_destroy(fixture.surface);
	for (unsigned int i = 0; i < fixture.n_buffers; i++)
		wl_buffer_destroy(fixture.buffers[i]);
	if (fixture.wm_base != NULL)
		xdg_wm_base_destroy(fixture.wm_base);
	if (fixture.shm != NULL)
		wl_shm_destroy(fixture.shm);
	if (fixture.compositor != NULL)
		wl_compositor_destroy(fixture.compositor);
	if (fixture.registry != NULL)
		wl_registry_destroy(fixture.registry);
	wl_display_disconnect(fixture.display);

	if (fixture.xkb_state != NULL)
		xkb_state_unref(fixture.xkb_state);
	if (fixture.xkb_keymap != NULL)
		xkb_keymap_unref(fixture.xkb_keymap);
	if (fixture.xkb_context != NULL)
		xkb_context_unref(fixture.xkb_context);

	return EXIT_SUCCESS;
}
