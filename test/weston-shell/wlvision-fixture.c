static void
keyboard_keymap(void *data, struct wl_keyboard *keyboard, uint32_t format,
		int32_t fd, uint32_t size)
{
	struct fixture *fixture = data;
	char *map;

	(void) keyboard;

	if (format != WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1 || size == 0) {
		close(fd);
		return;
	}

	map = mmap(NULL, size, PROT_READ, MAP_PRIVATE, fd, 0);
	if (map == MAP_FAILED) {
		close(fd);
		fatal(fixture, "keymap mmap failed: %s", strerror(errno));
	}

	if (fixture->xkb_keymap != NULL)
		xkb_keymap_unref(fixture->xkb_keymap);
	fixture->xkb_keymap = xkb_keymap_new_from_string(
		fixture->xkb_context, map, XKB_KEYMAP_FORMAT_TEXT_V1,
		XKB_KEYMAP_COMPILE_NO_FLAGS);
	munmap(map, size);
	close(fd);

	if (fixture->xkb_keymap == NULL) {
		fputs(REPORT_PREFIX "compositor keymap rejected\n", stderr);
		return;
	}

	if (fixture->xkb_state != NULL)
		xkb_state_unref(fixture->xkb_state);
	fixture->xkb_state = xkb_state_new(fixture->xkb_keymap);
	if (fixture->xkb_state == NULL)
		fatal(fixture, "xkb_state_new failed");
}

