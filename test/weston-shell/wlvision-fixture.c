/* ------------------------------------------------------------------ util */

static int64_t
now_ms(void)
{
	struct timespec ts;

	clock_gettime(CLOCK_MONOTONIC, &ts);
	return (int64_t) ts.tv_sec * 1000 + ts.tv_nsec / 1000000;
}

static void
report(const char *fmt, ...)
{
	va_list ap;

	fputs(REPORT_PREFIX, stdout);
	va_start(ap, fmt);
	vfprintf(stdout, fmt, ap);
	va_end(ap);
	fputc('\n', stdout);
	fflush(stdout);
}

static void
fatal(struct fixture *fixture, const char *fmt, ...)
{
	va_list ap;

	(void) fixture;

	fputs(REPORT_PREFIX, stderr);
	va_start(ap, fmt);
	vfprintf(stderr, fmt, ap);
	va_end(ap);
	fputc('\n', stderr);
	exit(EXIT_FAILURE);
}

