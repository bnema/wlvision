static int
compute_timeout(struct fixture *fixture, int64_t now)
{
	int64_t deadline = INT64_MAX;
	int64_t diff;

	if (fixture->resize_pending && fixture->resize_deadline < deadline)
		deadline = fixture->resize_deadline;
	if (fixture->exit_after_ms > 0 &&
	    fixture->start_ms + fixture->exit_after_ms < deadline)
		deadline = fixture->start_ms + fixture->exit_after_ms;
	if (fixture->grace_deadline != 0 && fixture->grace_deadline < deadline)
		deadline = fixture->grace_deadline;
	if (!fixture->animation_done && fixture->frame_ready &&
	    fixture->last_commit_ms + fixture->period_ms < deadline)
		deadline = fixture->last_commit_ms + fixture->period_ms;

	if (deadline == INT64_MAX)
		return -1;

	diff = deadline - now;
	if (diff < 0)
		diff = 0;
	if (diff > MAX_POLL_MS)
		diff = MAX_POLL_MS;
	return (int) diff;
}

static int
dispatch_once(struct fixture *fixture, int timeout)
{
	struct pollfd pfd;
	int ret;

	while (wl_display_prepare_read(fixture->display) != 0) {
		if (wl_display_dispatch_pending(fixture->display) < 0)
			return -1;
	}

	if (wl_display_flush(fixture->display) < 0 && errno != EAGAIN) {
		wl_display_cancel_read(fixture->display);
		return -1;
	}

	pfd.fd = wl_display_get_fd(fixture->display);
	pfd.events = POLLIN;
	pfd.revents = 0;
	ret = poll(&pfd, 1, timeout);
	if (ret < 0) {
		wl_display_cancel_read(fixture->display);
		return errno == EINTR ? 0 : -1;
	}
	if (ret == 0) {
		wl_display_cancel_read(fixture->display);
	} else if (pfd.revents & POLLIN) {
		if (wl_display_read_events(fixture->display) < 0)
			return -1;
	} else {
		wl_display_cancel_read(fixture->display);
		return -1;
	}

	if (wl_display_dispatch_pending(fixture->display) < 0)
		return -1;
	return 0;
}

static void
run(struct fixture *fixture)
{
	while (!fixture->done) {
		int64_t now = now_ms();

		/* One surface configure is the pair (xdg_surface.configure
		 * with the serial, xdg_toplevel.configure with the size and
		 * states); act once both halves of the newest pair are in. */
		if (fixture->have_surface_configure &&
		    fixture->have_toplevel_configure)
			handle_configure(fixture);

		if (fixture->resize_pending &&
		    now >= fixture->resize_deadline) {
			fixture->resize_pending = false;
			commit_frame(fixture, fixture->pending_width,
				     fixture->pending_height);
		}

		if (fixture->exit_after_ms > 0 &&
		    now - fixture->start_ms >= fixture->exit_after_ms)
			fixture->done = true;

		/* A client whose frame budget is done still waits for the
		 * resize configure its mode depends on; failing that, a short
		 * grace period keeps a compositor that never resizes from
		 * hanging the fixture forever. */
		if (fixture->animation_done && !fixture->resize_seen &&
		    !fixture->resize_pending &&
		    fixture->resize_mode != RESIZE_EXIT) {
			if (fixture->grace_deadline == 0)
				fixture->grace_deadline = now + ANIMATION_GRACE_MS;
			else if (now >= fixture->grace_deadline)
				fixture->done = true;
		}

		/* idle/ignore modes keep the window up quietly; the others are
		 * finished once their resize has settled. */
		if (fixture->animation_done && fixture->resize_seen &&
		    !fixture->resize_pending &&
		    fixture->resize_mode != RESIZE_NONE &&
		    fixture->resize_mode != RESIZE_EXIT)
			fixture->done = true;

		if (fixture->done)
			break;

		now = now_ms();
		if (!fixture->animation_done && fixture->frame_ready &&
		    now >= fixture->last_commit_ms + fixture->period_ms) {
			fixture->frame_ready = false;
			commit_frame(fixture, fixture->cur_width,
				     fixture->cur_height);
		}

		if (dispatch_once(fixture, compute_timeout(fixture, now_ms())) < 0) {
			fprintf(stderr, REPORT_PREFIX
				"display connection lost\n");
			break;
		}
	}
}

