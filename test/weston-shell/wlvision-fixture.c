static uint32_t
frame_colour(int frame)
{
	/* Knuth multiplicative hash of the frame index; deterministic. */
	return 0xff000000u | ((uint32_t) (frame * 2654435761u) & 0x00ffffffu);
}

static void
paint(uint32_t *pixels, int width, int height, int frame, bool animate)
{
	int rw;
	int rh;
	int span_x;
	int span_y;
	int x0;
	int y0;
	uint32_t colour;
	int x;
	int y;

	for (x = 0; x < width * height; x++)
		pixels[x] = BASE_COLOUR;

	if (!animate)
		return;

	/* One solid rectangle whose position and colour depend only on the
	 * frame index: consecutive animated frames differ byte for byte. */
	rw = width / 4 > 0 ? width / 4 : 1;
	rh = height / 4 > 0 ? height / 4 : 1;
	span_x = width - rw;
	span_y = height - rh;
	x0 = span_x > 0 ? (frame * 37) % span_x : 0;
	y0 = span_y > 0 ? (frame * 23) % span_y : 0;
	colour = frame_colour(frame);

	for (y = y0; y < y0 + rh && y < height; y++)
		for (x = x0; x < x0 + rw && x < width; x++)
			pixels[y * width + x] = colour;
}

static struct wl_buffer *
create_shm_buffer(struct fixture *fixture, int width, int height, int frame)
{
	struct wl_shm_pool *pool;
	struct wl_buffer *buffer;
	uint32_t *pixels;
	int stride = width * 4;
	int size = stride * height;
	int fd;

	fd = memfd_create("wlvision-fixture", MFD_CLOEXEC);
	if (fd < 0)
		fatal(fixture, "memfd_create failed: %s", strerror(errno));
	if (ftruncate(fd, size) < 0)
		fatal(fixture, "ftruncate failed: %s", strerror(errno));

	pixels = mmap(NULL, size, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
	if (pixels == MAP_FAILED)
		fatal(fixture, "mmap failed: %s", strerror(errno));
	paint(pixels, width, height, frame, fixture->animate);
	munmap(pixels, size);

	pool = wl_shm_create_pool(fixture->shm, fd, size);
	buffer = wl_shm_pool_create_buffer(pool, 0, width, height, stride,
					   WL_SHM_FORMAT_XRGB8888);
	wl_shm_pool_destroy(pool);
	close(fd);

	return buffer;
}

static void
frame_done(void *data, struct wl_callback *callback, uint32_t time)
{
	struct fixture *fixture = data;

	(void) time;

	/* Clear the pointer before destroying the proxy: wl_callback_destroy()
	 * would otherwise make the stale pointer look like a live callback. */
	fixture->frame_callback = NULL;
	wl_callback_destroy(callback);
	fixture->frame_ready = true;
}

static const struct wl_callback_listener frame_listener = {
	.done = frame_done,
};

static void
request_frame_callback(struct fixture *fixture)
{
	fixture->frame_callback = wl_surface_frame(fixture->surface);
	wl_callback_add_listener(fixture->frame_callback, &frame_listener,
				 fixture);
}

static void
commit_frame(struct fixture *fixture, int width, int height)
{
	struct wl_buffer *buffer;

	if (fixture->n_buffers == MAX_BUFFERS)
		fatal(fixture, "too many buffers");

	buffer = create_shm_buffer(fixture, width, height, fixture->frame_count + 1);
	fixture->buffers[fixture->n_buffers++] = buffer;

	wl_surface_attach(fixture->surface, buffer, 0, 0);
	wl_surface_damage(fixture->surface, 0, 0, width, height);
	if (!fixture->animation_done && fixture->frame_callback == NULL)
		request_frame_callback(fixture);
	wl_surface_commit(fixture->surface);

	fixture->frame_count++;
	fixture->cur_width = width;
	fixture->cur_height = height;
	fixture->last_commit_ms = now_ms();
	report("committed width=%d height=%d frame=%d", width, height,
	       fixture->frame_count);

	if (fixture->frame_count >= fixture->frames)
		fixture->animation_done = true;
}

