/*
 * wlvision-fixture.c - the deterministic native-Wayland fixture application
 * driven by the Phase 5 integration gates.
 *
 * One binary, flags select the behaviour: cooperative/delayed/ignored/exit
 * resize handling, animation bursts with a minimum inter-frame period, a
 * quiet screen that maps and then stops committing, and optional keyboard and
 * pointer event reporting through the compositor's own xkb keymap.
 *
 * The pending-frame loop is prepared-read/poll based and driven by
 * wl_surface.frame callbacks, so it never sleeps: nothing is committed until
 * the compositor has presented the previous frame.  The poll timeout only
 * exists to enforce the animation period, the delayed-resize deadline and the
 * --exit-after deadline, including on a compositor that would otherwise stop
 * sending frame callbacks because nothing has changed.
 *
 * Every committed buffer is drawn deterministically: a fixed base colour plus,
 * with --animate, one solid rectangle whose position and colour are a pure
 * function of the frame index.  No randomness and no clock enter the pixels.
 *
 * The xdg-shell bindings are generated by wayland-scanner from
 * wayland-protocols at image build time (see Containerfile); the protocol XML
 * is not hand-rolled.
 *
 * Copyright (C) 2026 wlvision
 * SPDX-License-Identifier: MIT
 */

